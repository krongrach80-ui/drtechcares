MetricKind = Literal[
    "shoulder_elevation",
    "elbow_flexion",
    "knee_extension",
    "hip_flexion",
    "heel_raise",
    "neck_lateral_tilt",
    "balance_trunk_sway",
    "trunk_flexion",
]


@dataclass(frozen=True)
class ClinicalExerciseRule:
    id: str
    code: str
    name_th: str
    name_en: str
    category: str
    side: Literal["left", "right", "both"]
    pattern: str
    metric_kind: MetricKind
    target_joint: str
    min_angle_deg: float
    max_angle_deg: float
    rest_angle_deg: float
    default_hold_sec: float
    default_sets: int
    default_reps: int
    anti_cheat_checks: Tuple[str, ...] = ("TRUNK_LEAN", "SHOULDER_HIKE", "TOO_FAST")

    @property
    def is_descending_target(self) -> bool:
        """True when active ROM decreases from rest angle (e.g., elbow flexion 145 -> 45)."""
        return self.min_angle_deg < self.rest_angle_deg


