export function sortExercisesStrokeUpperFirst<T extends ExerciseConfig>(exercises: ReadonlyArray<T>): T[] {
  const rank = (ex: T): number => {
    if (ex.clinicalFocus === 'stroke_adl') return 0;
    if (ex.clinicalFocus === 'moph_elderly') return 1;
    if (ex.category === 'upper_limb' || ex.category === 'neck_trunk') return 2;
    if (ex.category === 'balance') return 3;
    return 4;
  };
  return [...exercises].sort((a, b) => rank(a) - rank(b));
}

